import { mkdtemp, mkdir, copyFile, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { runPack } from './run.mjs';
const root = await mkdtemp(join(tmpdir(), 'proofshot-livesay-'));
const git = (dir, ...args) => execFileSync('git', ['-C',dir,...args], {encoding:'utf8'}).trim();
await mkdir(join(root,'build'));
await copyFile(new URL('./fixture/index.html',import.meta.url),join(root,'build','index.html'));
git(root,'init','-q');git(root,'add','build');
git(root,'-c','user.name=Synthetic Fixture','-c','user.email=fixture@example.invalid','commit','-qm','base fixture');
const baseCommit=git(root,'rev-parse','HEAD');
const base=await mkdtemp(join(tmpdir(),'proofshot-base-'));
git(root,'worktree','add','--detach',base,baseCommit);
const file=join(root,'build','index.html');
const text=await readFile(file,'utf8');
await writeFile(file,text.replace('Your report is ready. Completed.','Your report has changed. Completed.').replace('Result ready','Updated result'));
git(root,'add','build');git(root,'-c','user.name=Synthetic Fixture','-c','user.email=fixture@example.invalid','commit','-qm','head fixture');
const config={base:join(base,'build'),head:join(root,'build'),baseCommit,headCommit:git(root,'rev-parse','HEAD'),out:resolve(process.argv[3]??'livesay-pack-out'),viewport:{name:'mobile',width:390,height:844},scenes:[{name:'open-result',route:'/',steps:[{action:'click',selector:'#open'},{action:'wait',selector:'#result'}],expect:'#answer'}]};
const livesay=await import(pathToFileURL(resolve(process.argv[2])).href);
const pack=await runPack(config,livesay);
await writeFile(join(config.out,'rerun-config.json'),JSON.stringify({...config,out:config.out+'-rerun'},null,2));
if(pack.rows[0]?.visual?.status !== 'changed' || !pack.rows[0]?.visual?.a11y || JSON.stringify(pack.rows[0]?.transcripts?.base) === JSON.stringify(pack.rows[0]?.transcripts?.head)) throw new Error('Sample did not produce both visual/DOM evidence and transcript change');
console.log(JSON.stringify({root,out:config.out,status:pack.rows.map(r=>r.status)}));
if(pack.rows.some(r=>r.status!=='verified'))process.exitCode=1;
