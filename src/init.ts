import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";

export const WORKFLOW_PATH = ".github/workflows/proofshot.yml";

export interface InitOptions {
  cwd?: string;
  force?: boolean;
}

export interface InitResult {
  path: string;
  created: boolean;
  reason?: string;
}

/** Write the pull-request workflow that captures both sides and comments. */
export async function runInit(options: InitOptions = {}): Promise<InitResult> {
  const cwd = resolve(options.cwd ?? process.cwd());
  const file = join(cwd, WORKFLOW_PATH);
  if (existsSync(file) && !options.force) {
    return {
      path: file,
      created: false,
      reason: `${WORKFLOW_PATH} already exists (pass --force to overwrite)`,
    };
  }
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, renderWorkflowTemplate(), "utf8");
  return { path: file, created: true };
}

/**
 * Workflow template.
 *
 * Build-dir mode is the default because proofshot can serve both build outputs
 * itself — no dev server ports, no preview command to pin down.
 */
export function renderWorkflowTemplate(): string {
  return `# Generated by \`npx proofshot init\`.
# proofshot screenshots the base and head builds, diffs them, checks a11y, and
# writes proofshot-out/report.md. This workflow uploads that folder and posts
# the report as a PR comment (editing its previous comment, so it stays one).
name: proofshot

on:
  pull_request:

permissions:
  contents: read
  pull-requests: write

concurrency:
  group: proofshot-\${{ github.event.pull_request.number }}
  cancel-in-progress: true

env:
  # TODO: point these at your build output (Vite: dist, Next.js: out, CRA: build).
  BASE_DIR: ../proofshot-base/dist
  HEAD_DIR: ./dist
  # Pixel difference (percent) that counts as a change.
  THRESHOLD: "0.1"
  # Optional: comma-separated routes (\`--routes /\`). Omit to infer from the diff.
  ROUTES: ""

jobs:
  proofshot:
    runs-on: ubuntu-latest
    timeout-minutes: 20
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0

      - uses: actions/setup-node@v4
        with:
          node-version: 20
          cache: npm

      - name: Install dependencies
        run: npm ci

      - name: Install Playwright Chromium
        run: npx playwright install --with-deps chromium

      - name: Build head
        run: npm run build

      - name: Build base
        run: |
          git worktree add ../proofshot-base "\${{ github.event.pull_request.base.sha }}"
          cd ../proofshot-base
          npm ci
          npm run build

      - name: proofshot compare
        id: compare
        continue-on-error: true
        run: |
          npx -y proofshot compare \\
            --base "$BASE_DIR" \\
            --head "$HEAD_DIR" \\
            --base-ref "\${{ github.event.pull_request.base.sha }}" \\
            --head-ref "\${{ github.event.pull_request.head.sha }}" \\
            --threshold "$THRESHOLD" \\
            \${ROUTES:+--routes "$ROUTES"} \\
            --out proofshot-out

      - name: Upload evidence
        uses: actions/upload-artifact@v4
        with:
          name: proofshot-report
          path: proofshot-out
          retention-days: 14

      - name: Comment on pull request
        if: always()
        env:
          GH_TOKEN: \${{ github.token }}
        run: |
          if [ -f proofshot-out/report.md ]; then
            gh pr comment "\${{ github.event.pull_request.number }}" \\
              --body-file proofshot-out/report.md \\
              --edit-last --create-if-none
          fi
`;
}
